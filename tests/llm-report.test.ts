import assert from "node:assert";
import { test } from "node:test";
import { renderLlmReport } from "../evals/llm/report";
import type { CitationUnit } from "../evals/llm/citations";
import { modelSummary } from "../evals/llm/metrics";
import type { CallRecord } from "../evals/llm/recordingModel";
import { lookupPrice } from "../evals/llm/prices";
import type { LlmRunResult, RunOutcome } from "../evals/llm/run";

const call = (modelKey: string, over: Partial<CallRecord> = {}): CallRecord => ({
  caseId: "c", modelKey, purpose: "generation", role: "generate", hash: "h", cached: false, latencyMs: 1000,
  promptTokens: 1000, completionTokens: 500, thoughtsTokens: 100, modelVersion: "v1", temperature: 0.6, finishReason: "stop", responseText: "{}", ...over,
});
const unit = (index: number, idValid = true): CitationUnit => ({ index, path: `citations[${index - 1}]`, chunkId: `x${index}`, claim: "claim", idValid });

function outcome(caseId: string, modelKey: string, over: Partial<RunOutcome> = {}): RunOutcome {
  return {
    caseId, engine: "message", tags: ["baseline"], modelKey, ok: true, passed: true, failures: [],
    calls: [call(modelKey)], judgeCalls: [call("google:judge", { purpose: "judge", role: "judge", temperature: 0 })],
    units: [unit(1), unit(2)],
    judge: {
      ok: true, scores: { groundedness: 3, task_fit: 4, clarity: 2 }, reasons: { groundedness: "", task_fit: "", clarity: "" },
      claims: [{ claim: "a", status: "supported", evidence: "x" }, { claim: "b", status: "unsupported", evidence: "" }],
      citationVerdicts: { 1: "supports", 2: "partial" }, unjudged: [], ignoredVerdicts: 0,
    },
    ...over,
  };
}

function fixture(): LlmRunResult {
  const outcomes: RunOutcome[] = [
    outcome("case-1", "google:gemini-3.6-flash"),
    outcome("case-2", "google:gemini-3.6-flash", { passed: false, failures: ["bad | pipe\nnewline"] }),
    outcome("case-1", "google:other", { ok: false, passed: false, error: "boom AIzaSECRETSECRETSECRET", calls: [], judgeCalls: [], units: [], judge: undefined }),
    { ...outcome("case-2", "google:other"), notRun: "quota", ok: false, calls: [], judgeCalls: [], units: [], judge: undefined },
  ];
  const price = (k: string) => lookupPrice("google", k.split(":")[1]);
  const mine = (k: string) => outcomes.filter((o) => o.modelKey === k && !o.notRun);
  return {
    generatedAt: "2026-11-01T00:00:00.000Z", gitSha: "abc1234", command: "--models google:gemini-3.6-flash", node: "v22", platform: "win32 x64",
    harnessVersion: "llm-eval-1", caseFingerprint: "fp123", caseCount: 2, rubricHash: "rh456", priceTableRetrieved: "2026-11-01",
    models: [
      { key: "google:gemini-3.6-flash", provider: "google", requestedModel: "gemini-3.6-flash", reportedModelVersions: ["gemini-3.6-flash-001"], firstCallAt: "2026-11-01T00:00:00.000Z", freeTierKey: true },
      { key: "google:other", provider: "google", requestedModel: "other", reportedModelVersions: [], firstCallAt: null, freeTierKey: false },
      { key: "openai:x", provider: "openai", requestedModel: "x", reportedModelVersions: [], firstCallAt: null, freeTierKey: false, skipped: "no key for openai" },
    ],
    judge: { key: "google:judge", provider: "google", requestedModel: "judge", reportedModelVersions: ["judge-1"], freeTierKey: true },
    sampling: { observedTemperatures: { generate: [0.6], review: [0.2] }, judgeTemperature: 0, note: "other sampling settings are provider defaults; thinking settings provider default" },
    retrieval: "vault chunks selected by keyword BM25 (limit <= 12) or whole resume, as in the app without the semantic index",
    complete: false, caseSubset: false, outcomes,
    summaries: { "google:gemini-3.6-flash": modelSummary(mine("google:gemini-3.6-flash"), price), "google:other": modelSummary(mine("google:other"), price) },
    estimate: { perModel: [], judgeKey: null, judgeProbeCalls: 0, lower: 0, upper: 0, fallbackWorstCase: 0 },
  };
}

test("header: title, banner, provenance and the single-run statement", () => {
  const md = renderLlmReport(fixture());
  assert.ok(md.startsWith("# LLM evaluation\n\nGenerated by `npm run eval` — do not edit by hand. Numbers below come from evals/results/llm-latest.json of the same run."));
  for (const s of [
    "- Date: 2026-11-01T00:00:00.000Z", "- Git sha: abc1234", "- Node: v22", "- Platform: win32 x64", "- Harness version: llm-eval-1",
    "- Case fingerprint: fp123 (2 cases)", "- Rubric hash: rh456", "- Price table retrieved: 2026-11-01",
    "provider-reported: gemini-3.6-flash-001", "- Judge model: google judge; provider-reported: judge-1",
    "generate 0.6, review 0.2; judge 0;", "- Retrieval: vault chunks selected by keyword BM25",
    "Single run: each case ran once per model; numbers carry run-to-run variance.", "PARTIAL run",
  ]) assert.ok(md.includes(s), `missing: ${s}`);
  assert.ok(md.includes("openai x (skipped: no key for openai)"));
});

test("side-by-side table: row labels and computed cells", () => {
  const md = renderLlmReport(fixture());
  for (const label of [
    "Cases passed (n/N)", "Errors", "Citation id validity", "Citation precision (strict)", "Citation precision (lenient)", "Outputs with citations",
    "Claim fabrication rate (judged)", "Output fabrication rate (combined)", "Output fabrication rate (figure check only)",
    "Judge groundedness (mean 1-4)", "Judge task_fit (mean 1-4)", "Judge clarity (mean 1-4)", "Prompt tokens", "Completion tokens", "Thinking tokens",
    "Mean tokens per case", "p50 latency ms", "p95 latency ms", "Est. cost per case (USD, list price)", "Est. total cost (USD, list price)", "Billed on free tier (USD)",
  ]) assert.ok(md.includes(`| ${label} |`), `missing row ${label}`);
  const row = (label: string) => md.split("\n").find((l) => l.startsWith(`| ${label} |`)) as string;
  assert.ok(row("Cases passed (n/N)").includes("| 1/2 |"));
  assert.ok(row("Citation id validity").includes("100.0% (4/4)"));
  assert.ok(row("Citation precision (strict)").includes("50.0% (2/4)"));
  assert.ok(row("Citation precision (lenient)").includes("100.0% (4/4)"));
  assert.ok(row("Claim fabrication rate (judged)").includes("50.0% (2/4)"));
  assert.ok(row("Judge groundedness (mean 1-4)").includes("3.00"));
  assert.ok(row("Prompt tokens").includes("2,000"));
  assert.ok(row("Billed on free tier (USD)").includes("0.00"));
  assert.ok(row("Billed on free tier (USD)").trimEnd().endsWith("n/a |"), "non-free-tier key shows n/a");
  assert.ok(row("Citation precision (strict)").includes("n/a"), "model with no judged output shows n/a, not 0");
});

test("judge cost, guardrails and per-case table", () => {
  const md = renderLlmReport(fixture());
  assert.ok(md.includes("## Judge cost"));
  assert.ok(md.includes("Judging google:gemini-3.6-flash outputs with google:judge: 2,000 prompt, 1,000 completion, 200 thinking tokens"));
  assert.ok(md.includes("## Guardrail activity"));
  assert.ok(md.includes("| Case | Engine | Tags |"));
  assert.ok(md.includes("| case-1 | message | baseline |"));
  assert.ok(md.includes("pass · 1,600 tok · 1000 ms"));
  assert.ok(md.includes("not run"));
  assert.ok(md.includes("G/T/C 3/4/2"));
});

test("failures list: pipes escaped, newlines collapsed, secrets redacted", () => {
  const md = renderLlmReport(fixture());
  const failures = md.slice(md.indexOf("### Failures and errors"));
  assert.ok(failures.includes("bad \\| pipe newline"));
  assert.ok(failures.includes("error: boom [REDACTED]"));
  assert.ok(!md.includes("AIzaSECRET"));
});

test("fixed sections: agreement pending, definitions, limitations", () => {
  const md = renderLlmReport(fixture());
  assert.ok(md.includes("## Judge agreement with human labels\n\nPending: hand labels not yet collected (see evals/llm/labels/)."));
  assert.ok(md.includes("## Definitions") && md.includes("evals/llm/RUBRIC.md"));
  assert.ok(md.includes("## Limitations"));
  assert.ok(md.includes("same provider family"), "self-preference stated when judge shares a generator provider");
  assert.ok(md.includes("keyword-only"));
  const noJudge = renderLlmReport({ ...fixture(), judge: null });
  assert.ok(noJudge.includes("no judge in this run"));
});

test("rendering is deterministic", () => {
  assert.strictEqual(renderLlmReport(fixture()), renderLlmReport(fixture()));
});
