// Renders evals/PROFILE.md. Pure and deterministic: no Date, no fs.
import { FIELD_KEYS, prf, type FieldCounts } from "./metrics";

/** Measured by `npm run eval:profile -- --llm` (see evals/profile/llm.ts). */
export interface LlmProfileModelResult {
  key: string;
  refined: FieldCounts;
  llmOnly: FieldCounts;
  resumesDone: number;
  resumesTotal: number;
  stoppedByQuota: boolean;
  usage: { promptTokens: number; completionTokens: number };
}
export interface LlmProfileSection {
  status: "measured" | "partial";
  models: LlmProfileModelResult[];
}

export interface ProfileRunResult {
  generatedAt: string;
  command: string;
  gitSha: string;
  node: string;
  platform: string;
  datasetFingerprint: string;
  extractorVersion: string;
  taxonomyVersion: string;
  resumes: { id: string; source: "rendered" | "synthetic"; styleId: string | null; counts: FieldCounts }[];
  overall: FieldCounts;
  bySource: { rendered: FieldCounts; synthetic: FieldCounts };
  llm: { status: "pending" } | LlmProfileSection;
}

const f3 = (v: number | null) => (v === null ? "n/a" : v.toFixed(3));
const rate = (r: { hit: number; total: number }) => (r.total > 0 ? f3(r.hit / r.total) : "n/a");

function fieldTable(c: FieldCounts): string[] {
  const lines = ["| Field | Precision | Recall | F1 | Support |", "| --- | ---: | ---: | ---: | ---: |"];
  for (const k of FIELD_KEYS) {
    const m = prf(c[k]);
    lines.push(`| ${k} | ${f3(m.precision)} | ${f3(m.recall)} | ${f3(m.f1)} | ${m.support} |`);
  }
  return lines;
}

function macroF1(c: FieldCounts): string {
  const vals = FIELD_KEYS.map((k) => prf(c[k]).f1).filter((v): v is number => v !== null);
  return vals.length ? f3(vals.reduce((a, b) => a + b, 0) / vals.length) : "n/a";
}

export const LLM_PENDING_TEXT =
  "Pending: run after Phase 3 completes (`npm run eval:profile -- --llm`). Not measured in this phase because the free-tier quota is in use by the Phase 3 scheduled evaluation.";

function renderLlm(llm: LlmProfileSection, det: FieldCounts): string[] {
  const out: string[] = [];
  out.push(llm.status === "partial" ? "Partial measurement: some resumes were not run (see each model below). Re-run to resume from the cache." : "Measured with the same metrics as the deterministic extractor.", "");
  for (const m of llm.models) {
    out.push(`### ${m.key}`, "");
    out.push(`- Resumes done: ${m.resumesDone}/${m.resumesTotal}`);
    if (m.stoppedByQuota) out.push("- Stopped early: daily quota exhausted. Completed resumes are cached; re-run after the quota resets.");
    out.push(`- Tokens: ${m.usage.promptTokens} prompt, ${m.usage.completionTokens} completion`, "");
    out.push("Refined (deterministic + LLM merge) versus deterministic only:", "");
    out.push("| Field | Det P | Det R | Refined P | Refined R | Refined F1 | F1 change |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
    for (const k of FIELD_KEYS) {
      const d = prf(det[k]);
      const x = prf(m.refined[k]);
      const delta = d.f1 === null || x.f1 === null ? "n/a" : (x.f1 - d.f1 >= 0 ? "+" : "") + (x.f1 - d.f1).toFixed(3);
      out.push(`| ${k} | ${f3(d.precision)} | ${f3(d.recall)} | ${f3(x.precision)} | ${f3(x.recall)} | ${f3(x.f1)} | ${delta} |`);
    }
    out.push("", "LLM only:", "", ...fieldTable(m.llmOnly), "");
  }
  return out;
}

export function renderProfileReport(r: ProfileRunResult): string {
  const out: string[] = [];
  out.push("# Profile extraction accuracy", "");
  out.push("Generated by `npm run eval:profile` — do not edit by hand. Numbers below come from evals/results/profile-latest.json of the same run.", "");
  out.push(`- Date: ${r.generatedAt}`);
  out.push(`- Git sha: ${r.gitSha}`);
  out.push(`- Node: ${r.node}`);
  out.push(`- Platform: ${r.platform}`);
  out.push(`- Command: ${r.command || "(none)"}`);
  out.push(`- Dataset fingerprint: ${r.datasetFingerprint}`);
  out.push(`- Extractor version: ${r.extractorVersion}`);
  out.push(`- Taxonomy version: ${r.taxonomyVersion}`, "");

  out.push("## Deterministic extractor: overall", "");
  out.push(`Resumes: ${r.resumes.length}. Macro-F1 across fields with support: ${macroF1(r.overall)}.`, "");
  out.push(...fieldTable(r.overall), "");

  out.push("## Exact match", "");
  out.push("| Unit | Exact | Rate |", "| --- | ---: | ---: |");
  out.push(`| Contact block (all four scalar fields exact) | ${r.overall.exact.contact.hit}/${r.overall.exact.contact.total} | ${rate(r.overall.exact.contact)} |`);
  out.push(`| Roles (title, company, start, end all exact) | ${r.overall.exact.roles.hit}/${r.overall.exact.roles.total} | ${rate(r.overall.exact.roles)} |`, "");

  out.push("## Per resume", "");
  out.push("| Resume | Source | Style | Roles exact | Contact exact | Company P | Company R | Start R | Skills P | Skills R |");
  out.push("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const x of r.resumes) {
    const co = prf(x.counts["roles.company"]);
    const st = prf(x.counts["roles.start"]);
    const sk = prf(x.counts["skills.canonical"]);
    out.push(
      `| ${x.id} | ${x.source} | ${x.styleId ?? "-"} | ${x.counts.exact.roles.hit}/${x.counts.exact.roles.total} | ${x.counts.exact.contact.hit}/${x.counts.exact.contact.total} | ${f3(co.precision)} | ${f3(co.recall)} | ${f3(st.recall)} | ${f3(sk.precision)} | ${f3(sk.recall)} |`,
    );
  }
  out.push("");

  out.push("## Rendered versus synthetic", "");
  out.push("| Source | Macro-F1 | Roles exact | Contact exact |", "| --- | ---: | ---: | ---: |");
  for (const s of ["rendered", "synthetic"] as const) {
    const c = r.bySource[s];
    out.push(`| ${s} | ${macroF1(c)} | ${rate(c.exact.roles)} | ${rate(c.exact.contact)} |`);
  }
  out.push("");

  out.push("## LLM-refined extraction", "");
  if (r.llm.status === "pending") out.push(LLM_PENDING_TEXT, "");
  else out.push(...renderLlm(r.llm, r.overall), "");

  out.push("## Protocol", "");
  out.push("- Gold labels for rendered resumes are known by construction: profiles were authored first, then rendered into resume text by evals/profile/dataset/render.ts.");
  out.push("- Gold for the synthetic resumes is hand-written.");
  out.push("- The extractor was written without access to this dataset.");
  out.push('- These are the first measured numbers and are reported as measured; the extractor was not tuned against the gold set. Any later extractor change must bump the extractor version and record before/after numbers in a "Changes since first measurement" section.');
  out.push("- Known limitation: the rendered formats were written by the same project, so they may be easier than real-world resumes.");
  out.push("- Precision and recall are micro-averaged over all resumes; n/a means the denominator was empty.", "");
  return out.join("\n");
}
