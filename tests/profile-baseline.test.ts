// Profile baseline gating and report rendering. Pure.
import assert from "node:assert";
import { test } from "node:test";
import { PROFILE_EPSILON, compareProfileBaseline, validateProfileBaseline, type ProfileBaseline } from "../evals/profile/baseline";
import { FIELD_KEYS, aggregateCounts, scoreProfile } from "../evals/profile/metrics";
import { renderProfileReport, type ProfileRunResult } from "../evals/profile/report";
import { emptyProfile } from "../lib/profile/schema";

function makeBase(): ProfileBaseline {
  const fields = {} as ProfileBaseline["fields"];
  for (const k of FIELD_KEYS) fields[k] = { precision: 0.9, recall: 0.8, support: 10 };
  fields["education.endYear"] = { precision: null, recall: null, support: 0 };
  return { kind: "profile-deterministic", fingerprint: "abc", extractorVersion: "det-1", taxonomyVersion: "skills-1", recordedAt: "2026-01-01T00:00:00Z", fields, exact: { contact: 0.5, roles: 0.6 } };
}
const strip = (b: ProfileBaseline): Omit<ProfileBaseline, "recordedAt"> => {
  const copy = JSON.parse(JSON.stringify(b)) as Partial<ProfileBaseline>;
  delete copy.recordedAt;
  return copy as Omit<ProfileBaseline, "recordedAt">;
};

test("identical current passes with no improvements", () => {
  const b = makeBase();
  const cmp = compareProfileBaseline(b, strip(b));
  assert.equal(cmp.ok, true);
  assert.deepEqual(cmp.improvements, []);
  assert.equal(PROFILE_EPSILON, 0.005);
});

test("degraded roles.company recall fails and names field and values", () => {
  const b = makeBase();
  const cur = strip(b);
  cur.fields["roles.company"].recall = 0.7;
  const cmp = compareProfileBaseline(b, cur);
  assert.equal(cmp.ok, false);
  assert.ok(cmp.regressions.some((r) => r.includes("roles.company recall") && r.includes("0.7000") && r.includes("0.8000")));
});

test("a rise is an improvement; a drop within epsilon is fine", () => {
  const b = makeBase();
  const cur = strip(b);
  cur.fields["contact.name"].precision = 0.95;
  cur.fields["contact.email"].recall = 0.8 - 0.004;
  const cmp = compareProfileBaseline(b, cur);
  assert.equal(cmp.ok, true);
  assert.equal(cmp.improvements.length, 1);
});

test("a metric disappearing is a regression", () => {
  const b = makeBase();
  const cur = strip(b);
  cur.fields["roles.title"].precision = null;
  const cmp = compareProfileBaseline(b, cur);
  assert.equal(cmp.ok, false);
  assert.ok(cmp.regressions.some((r) => r.includes("metric disappeared")));
});

test("exact-match rates are gated", () => {
  const b = makeBase();
  const cur = strip(b);
  cur.exact.roles = 0.3;
  assert.equal(compareProfileBaseline(b, cur).ok, false);
});

test("fingerprint and version mismatches fail with the update instruction", () => {
  const b = makeBase();
  for (const patch of [{ fingerprint: "zzz" }, { extractorVersion: "det-2" }, { taxonomyVersion: "skills-2" }]) {
    const cmp = compareProfileBaseline(b, { ...strip(b), ...patch });
    assert.equal(cmp.ok, false);
    assert.equal(cmp.fingerprintMismatch, true);
    assert.ok(cmp.regressions.some((r) => r.includes("npm run eval:profile -- --update-baseline --dataset-changed")));
  }
});

test("validateProfileBaseline rejects malformed input", () => {
  assert.equal(validateProfileBaseline("x").ok, false);
  assert.equal(validateProfileBaseline(null).ok, false);
  const b = makeBase();
  assert.equal(validateProfileBaseline(b).ok, true);
  assert.equal(validateProfileBaseline({ ...b, fingerprint: "" }).ok, false);
  assert.equal(validateProfileBaseline({ ...b, kind: "keyword" }).ok, false);
  const bad = JSON.parse(JSON.stringify(b));
  bad.fields["roles.title"].precision = "high";
  assert.equal(validateProfileBaseline(bad).ok, false);
});

function sampleResult(): ProfileRunResult {
  const g = emptyProfile();
  g.contact.name = "Jane Doe";
  const counts = scoreProfile(g, g);
  return {
    generatedAt: "2026-11-01T00:00:00.000Z",
    command: "",
    gitSha: "abc1234",
    node: "v22",
    platform: "linux x64",
    datasetFingerprint: "fp123",
    extractorVersion: "det-1",
    taxonomyVersion: "skills-1",
    resumes: [{ id: "r1", source: "rendered", styleId: "s1", counts }],
    overall: aggregateCounts([counts]),
    bySource: { rendered: aggregateCounts([counts]), synthetic: aggregateCounts([]) },
    llm: { status: "pending" },
  };
}

test("report has required structure and is deterministic", () => {
  const a = renderProfileReport(sampleResult());
  assert.ok(a.startsWith("# Profile extraction accuracy"));
  assert.ok(a.includes("Generated by `npm run eval:profile` — do not edit by hand."));
  for (const s of ["abc1234", "fp123", "det-1", "skills-1", "| Field | Precision | Recall | F1 | Support |", "n/a", "## Protocol", "## LLM-refined extraction", "## Per resume", "## Exact match"]) {
    assert.ok(a.includes(s), s);
  }
  assert.ok(a.includes("Pending: run after Phase 3 completes (`npm run eval:profile -- --llm`). Not measured in this phase because the free-tier quota is in use by the Phase 3 scheduled evaluation."));
  assert.equal(a, renderProfileReport(sampleResult()));
});
