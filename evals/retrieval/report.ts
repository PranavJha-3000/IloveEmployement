// Renders evals/RETRIEVAL.md purely from a RetrievalRunResult. No hand-typed numbers.
import { METRIC_KEYS } from "./metrics";
import type { MetricSet } from "./metrics";
import type { RetrievalRunResult } from "./run";

const f3 = (n: number) => n.toFixed(3);
const f2 = (n: number) => n.toFixed(2);

function metricTable(result: RetrievalRunResult, pick: (s: RetrievalRunResult["strategies"][number]) => MetricSet): string[] {
  const header = METRIC_KEYS.map((k) => (k === result.primaryMetric ? `**${k}**` : k));
  const lines = [`| Strategy | ${header.join(" | ")} |`, `| --- | ${METRIC_KEYS.map(() => "---:").join(" | ")} |`];
  for (const s of result.strategies) {
    lines.push(`| ${s.label} | ${METRIC_KEYS.map((k) => f3(pick(s)[k])).join(" | ")} |`);
  }
  return lines;
}

export function renderReport(result: RetrievalRunResult): string {
  const out: string[] = [];
  const d = result.dataset;
  out.push("# Retrieval evaluation", "");
  out.push(
    "Generated by `npm run eval:retrieval` — do not edit by hand. Numbers below come from evals/results/retrieval-latest.json of the same run.",
    "",
  );
  out.push(
    `- Date: ${result.generatedAt}`,
    `- Git sha: ${result.gitSha}`,
    `- Node: ${result.node}`,
    `- Platform: ${result.platform}`,
    `- Embedding model: ${result.embeddingModel ? `${result.embeddingModel.id} (${result.embeddingModel.dtype})` : "not used in this run"}`,
    `- Dataset fingerprint: ${d.fingerprint}`,
    "",
  );

  out.push("## Dataset", "");
  out.push("| Resume | Seniority | Domain | Chunks |", "| --- | --- | --- | ---: |");
  for (const r of d.resumes) out.push(`| ${r.id} | ${r.seniority} | ${r.domain} | ${r.chunks} |`);
  out.push("", `${d.queries} queries: ${d.lexical} lexical, ${d.paraphrase} paraphrase.`, "");

  out.push("## Method", "");
  out.push(
    "- Each resume is its own corpus, as in the app's single-user vault.",
    "- Strategies call retrieveVault / semanticRanking / reciprocalRankFusion from lib/, the same code the app runs.",
    "- Limit 8 = DEFAULT_VAULT_LIMIT.",
    "- The app always anchors the summary at rank 1 and keeps at most 3 chunks per role; the metrics include that behaviour.",
    `- Relevance grades 1-3; recall and MRR count grade >= ${result.relevanceThreshold}; nDCG gain is 2^g - 1. MRR is effectively MRR@8.`,
    `- Latency is the median of ${result.repeat} timed calls per query, including the query embedding for embedding strategies; chunk vectors are precomputed as in the app's index.`,
    `- Primary metric is ${result.primaryMetric}: it is graded, covers the full 8-chunk context and is order-sensitive.`,
    "",
  );

  out.push("## Overall", "", ...metricTable(result, (s) => s.overall), "");
  out.push("## Lexical queries", "", ...metricTable(result, (s) => s.byType.lexical), "");
  out.push("## Paraphrase queries", "", ...metricTable(result, (s) => s.byType.paraphrase), "");

  out.push("## By resume", "", `Primary metric (${result.primaryMetric}).`, "");
  const resumeIds = d.resumes.map((r) => r.id);
  out.push(`| Strategy | ${resumeIds.join(" | ")} |`, `| --- | ${resumeIds.map(() => "---:").join(" | ")} |`);
  for (const s of result.strategies) {
    out.push(`| ${s.label} | ${resumeIds.map((id) => f3(s.byResume[id]?.[result.primaryMetric as keyof MetricSet] ?? 0)).join(" | ")} |`);
  }
  out.push("");

  out.push("## Latency", "", "| Strategy | p50 ms | p95 ms | Query-embed p50 ms |", "| --- | ---: | ---: | ---: |");
  for (const s of result.strategies) out.push(`| ${s.label} | ${f2(s.latency.p50)} | ${f2(s.latency.p95)} | ${f2(s.latency.embedP50)} |`);
  out.push("");

  out.push("## Misses", "", "Queries where every strategy has recall@8 = 0.", "");
  const queryCount = result.strategies[0]?.perQuery.length ?? 0;
  const misses: string[] = [];
  for (let i = 0; i < queryCount; i++) {
    if (result.strategies.every((s) => s.perQuery[i].metrics["recall@8"] === 0)) {
      const q = result.strategies[0].perQuery[i];
      misses.push(`- ${q.id} (${q.type}): ${q.query}`);
    }
  }
  out.push(...(misses.length ? misses : ["No queries missed by every strategy."]), "");
  return out.join("\n");
}
