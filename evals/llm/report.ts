// Renders evals/LLM.md purely from an LlmRunResult. No clock, no fs, no hand-typed numbers.
import { redactSecrets } from "../../lib/pipeline";
import { caseMetrics, type CaseMetrics } from "./metrics";
import { lookupPrice, PRICE_TABLE_NOTE } from "./prices";
import type { LlmRunResult, ModelInfo, RunOutcome } from "./run";

const priceFor = (modelKey: string) => {
  const i = modelKey.indexOf(":");
  return i > 0 ? lookupPrice(modelKey.slice(0, i), modelKey.slice(i + 1)) : null;
};

const NA = "n/a";
const int = (n: number | null) => (n === null ? NA : Math.round(n).toLocaleString("en-US"));
const usd = (n: number | null) => (n === null ? NA : `$${n.toFixed(4)}`);
const score = (n: number | null) => (n === null ? NA : n.toFixed(2));
const rate = (num: number, den: number) => (den > 0 ? `${((num / den) * 100).toFixed(1)}% (${num}/${den})` : NA);
const esc = (s: string) => redactSecrets(s).replace(/\r?\n/g, " ").replace(/\|/g, "\\|");

interface Row {
  outcome: RunOutcome;
  m: CaseMetrics;
}

function rowsFor(result: LlmRunResult, key: string): Row[] {
  return result.outcomes
    .filter((o) => o.modelKey === key && !o.notRun)
    .map((o) => ({ outcome: o, m: caseMetrics(o, priceFor) }));
}

function table(header: string[], rows: string[][]): string[] {
  return [`| ${header.join(" | ")} |`, `| ${header.map((_, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)];
}

function cell(r: Row | undefined, notRun: boolean): string {
  if (!r) return notRun ? "not run" : NA;
  const { outcome: o, m } = r;
  const result = !o.ok ? "error" : o.passed ? "pass" : "FAIL";
  const judged = m.citation.judged;
  const den = m.citation.units - m.citation.unjudged;
  const strict = judged && m.citation.units > 0 && den > 0 ? `${m.citation.supports}/${den}` : NA;
  const unsupported = judged ? String(m.fabrication.unsupportedClaims) : NA;
  const j = o.judge?.ok ? `${o.judge.scores.groundedness}/${o.judge.scores.task_fit}/${o.judge.scores.clarity}` : NA;
  return `${result} · ${int(m.tokens.total)} tok · ${m.latencyMs === null ? NA : `${Math.round(m.latencyMs)} ms`} · ${usd(m.costUsd)} · cit ${strict} · unsup ${unsupported} · G/T/C ${j}`;
}

export function renderLlmReport(result: LlmRunResult): string {
  const out: string[] = [];
  const active: ModelInfo[] = result.models.filter((m) => !m.skipped);
  const skipped = result.models.filter((m) => m.skipped);

  out.push("# LLM evaluation", "");
  out.push(
    "Generated by `npm run eval` — do not edit by hand. Numbers below come from evals/results/llm-latest.json of the same run.",
    "",
  );

  const temps = Object.entries(result.sampling.observedTemperatures)
    .map(([role, ts]) => `${role} ${ts.join("/")}`)
    .join(", ");
  out.push(
    `- Date: ${result.generatedAt}`,
    `- Git sha: ${result.gitSha}`,
    `- Node: ${result.node}`,
    `- Platform: ${result.platform}`,
    `- Command: ${result.command ? `\`${esc(result.command)}\`` : "(not recorded)"}`,
    `- Harness version: ${result.harnessVersion}`,
    `- Case fingerprint: ${result.caseFingerprint} (${result.caseCount} cases)`,
    `- Rubric hash: ${result.rubricHash}`,
    `- Price table retrieved: ${result.priceTableRetrieved}`,
  );
  for (const m of result.models) {
    out.push(
      m.skipped
        ? `- Generator model: ${m.provider} ${m.requestedModel} (skipped: ${esc(m.skipped)})`
        : `- Generator model: ${m.provider} ${m.requestedModel}; provider-reported: ${m.reportedModelVersions.length ? m.reportedModelVersions.join(", ") : "not reported"}`,
    );
  }
  out.push(
    result.judge
      ? `- Judge model: ${result.judge.provider} ${result.judge.requestedModel}; provider-reported: ${result.judge.reportedModelVersions.length ? result.judge.reportedModelVersions.join(", ") : "not reported"}`
      : `- Judge model: no judge in this run${result.judgeNote ? ` (${esc(result.judgeNote)})` : ""}`,
    `- Sampling: observed temperatures by role: ${temps || "none recorded"}; judge ${result.sampling.judgeTemperature}; ${result.sampling.note}`,
    `- Retrieval: ${result.retrieval}`,
    `- Coverage: ${result.complete ? "full case set" : "PARTIAL run (not every case was attempted); this is a preview"}`,
    "- Single run: each case ran once per model; numbers carry run-to-run variance.",
    "",
  );

  // ── Models side by side ──
  out.push("## Models side by side", "");
  if (!active.length) {
    out.push("No model produced results in this run.", "");
  } else {
    const per = active.map((m) => {
      const rows = rowsFor(result, m.key);
      const s = result.summaries[m.key];
      const okRows = rows.filter((r) => r.outcome.ok);
      const judged = rows.filter((r) => r.m.citation.judged);
      const allUnits = okRows.reduce((n, r) => n + r.m.citation.units, 0);
      const validUnits = okRows.reduce((n, r) => n + r.m.citation.validIds, 0);
      const jden = judged.reduce((n, r) => n + r.m.citation.units - r.m.citation.unjudged, 0);
      const supports = judged.reduce((n, r) => n + r.m.citation.supports, 0);
      const partial = judged.reduce((n, r) => n + r.m.citation.partial, 0);
      const supC = judged.reduce((n, r) => n + r.m.fabrication.supportedClaims, 0);
      const unsC = judged.reduce((n, r) => n + r.m.fabrication.unsupportedClaims, 0);
      const combined = judged.filter((r) => r.m.fabrication.combinedFlag === true).length;
      const figure = judged.filter((r) => r.m.fabrication.figureFlag).length;
      return { m, rows, s, okRows, judged, allUnits, validUnits, jden, supports, partial, supC, unsC, combined, figure };
    });
    const line = (label: string, f: (p: (typeof per)[number]) => string) => [label, ...per.map(f)];
    const costNote = (p: (typeof per)[number], v: number | null) =>
      v === null ? NA : p.s.costUnknownCases > 0 ? `${usd(v)} (${p.s.costKnownCases} of ${p.s.cases} cases priced)` : usd(v);
    const rows: string[][] = [
      line("Cases passed (n/N)", (p) => `${p.s.passed}/${p.s.cases}`),
      line("Errors", (p) => String(p.s.errors)),
      line("Citation id validity", (p) => rate(p.validUnits, p.allUnits)),
      line("Citation precision (strict)", (p) => rate(p.supports, p.jden)),
      line("Citation precision (lenient)", (p) => rate(p.supports + p.partial, p.jden)),
      line("Outputs with citations", (p) => `${p.s.outputsWithUnits}/${p.okRows.length}`),
      line("Claim fabrication rate (judged)", (p) => rate(p.unsC, p.supC + p.unsC)),
      line("Output fabrication rate (combined)", (p) => rate(p.combined, p.judged.length)),
      line("Output fabrication rate (figure check only)", (p) => rate(p.figure, p.judged.length)),
      line("Judge groundedness (mean 1-4)", (p) => score(p.s.judgeMeans.groundedness)),
      line("Judge task_fit (mean 1-4)", (p) => score(p.s.judgeMeans.task_fit)),
      line("Judge clarity (mean 1-4)", (p) => score(p.s.judgeMeans.clarity)),
      line("Prompt tokens", (p) => int(p.s.tokens.prompt)),
      line("Completion tokens", (p) => int(p.s.tokens.completion)),
      line("Thinking tokens", (p) => (p.s.tokens.thoughts > 0 ? int(p.s.tokens.thoughts) : "0 (none reported)")),
      line("Mean tokens per case", (p) => int(p.s.tokens.meanPerCase)),
      line("p50 latency ms", (p) => int(p.s.latencyP50Ms)),
      line("p95 latency ms", (p) => int(p.s.latencyP95Ms)),
      line("Est. cost per case (USD, list price)", (p) => costNote(p, p.s.costPerCaseUsd)),
      line("Est. total cost (USD, list price)", (p) => costNote(p, p.s.costTotalUsd)),
      line("Billed on free tier (USD)", (p) => (p.m.freeTierKey ? "0.00" : NA)),
    ];
    out.push(...table(["Metric", ...active.map((m) => `${m.provider} ${m.requestedModel}`)], rows), "");
    out.push(PRICE_TABLE_NOTE, "");
  }
  if (skipped.length) {
    out.push("Skipped models:", ...skipped.map((m) => `- ${m.key}: ${esc(m.skipped ?? "")}`), "");
  }

  // ── Judge cost ──
  out.push("## Judge cost", "");
  if (!result.judge) {
    out.push("No judge in this run.", "");
  } else {
    for (const m of active) {
      const s = result.summaries[m.key];
      if (!s) continue;
      out.push(
        `- Judging ${m.key} outputs with ${result.judge.key}: ${int(s.judgeTokens.prompt)} prompt, ${int(s.judgeTokens.completion)} completion, ${int(s.judgeTokens.thoughts)} thinking tokens; est. cost ${usd(s.judgeCostTotalUsd)}${s.judgeCostUnknownOutputs > 0 ? ` (${s.judgeCostUnknownOutputs} output(s) unpriced)` : ""}. Not included in the generator totals above.`,
      );
    }
    out.push("");
  }

  // ── Guardrail activity ──
  out.push("## Guardrail activity", "");
  if (active.length) {
    const g = active.map((m) => {
      const rows = rowsFor(result, m.key);
      const sum = (f: (c: CaseMetrics) => number) => rows.reduce((n, r) => n + f(r.m), 0);
      return [
        `${m.provider} ${m.requestedModel}`,
        String(sum((c) => c.guardrails.injectionFlags)),
        String(sum((c) => c.guardrails.droppedCitations)),
        String(sum((c) => c.guardrails.unsupportedFigureWarnings)),
        String(sum((c) => c.guardrails.reviewIssues)),
        String(sum((c) => (c.guardrails.revised ? 1 : 0))),
      ];
    });
    out.push(...table(["Model", "Injection flags", "Dropped citations", "Figure warnings", "Reviewer issues (high/medium)", "Revisions"], g), "");
  } else out.push("No results.", "");

  // ── Per case ──
  out.push("## Per case", "");
  out.push("Each cell: result · tokens · latency · est. cost · citation precision (supports/judged) · unsupported claims · judge groundedness/task_fit/clarity.", "");
  const caseIds: string[] = [];
  for (const o of result.outcomes) if (!caseIds.includes(o.caseId)) caseIds.push(o.caseId);
  const caseRows = caseIds.map((id) => {
    const first = result.outcomes.find((o) => o.caseId === id)!;
    return [
      id,
      first.engine,
      first.tags.join(", ") || "-",
      ...active.map((m) => {
        const o = result.outcomes.find((x) => x.caseId === id && x.modelKey === m.key);
        return cell(o && !o.notRun ? { outcome: o, m: caseMetrics(o, priceFor) } : undefined, Boolean(o?.notRun));
      }),
    ];
  });
  out.push(...table(["Case", "Engine", "Tags", ...active.map((m) => `${m.provider} ${m.requestedModel}`)], caseRows), "");

  out.push("### Failures and errors", "");
  const bad = result.outcomes.filter((o) => !o.notRun && (!o.ok || !o.passed || o.judge?.ok === false));
  if (!bad.length) out.push("None.", "");
  else {
    for (const o of bad) {
      const notes = [
        ...(o.error ? [`error: ${o.error}`] : []),
        ...o.failures,
        ...(o.judge && !o.judge.ok ? [`judge failed: ${o.judge.error}`] : []),
      ];
      out.push(`- ${esc(o.caseId)} (${esc(o.modelKey)}): ${notes.map(esc).join("; ") || "failed"}`);
    }
    out.push("");
  }

  // ── Agreement ──
  out.push("## Judge agreement with human labels", "");
  out.push(
    result.agreement
      ? "Computed from hand labels; see the agreement block in evals/results/llm-latest.json."
      : "Pending: hand labels not yet collected (see evals/llm/labels/).",
    "",
  );

  // ── Definitions ──
  out.push("## Definitions", "");
  out.push(
    "Full definitions and the judge rubric are in [evals/llm/RUBRIC.md](llm/RUBRIC.md).",
    "",
    "- Citation precision (strict) = citation units with a supplied id and judge verdict `supports` / (all units minus unjudged units).",
    "- Output fabrication rate (combined) = judged outputs with at least one unsupported claim or an invented-figure warning / judged outputs.",
    "",
  );

  // ── Limitations ──
  out.push("## Limitations", "");
  const selfJudge = result.judge && result.models.some((m) => m.provider === result.judge!.provider);
  out.push(
    selfJudge
      ? `- The judge (${result.judge!.provider}) is in the same provider family as at least one generator, so self-preference bias is possible.`
      : "- The judge is a single model; its own biases are not measured here.",
    "- Each case ran once per model, so there is no run-to-run variance estimate.",
    "- Small n per engine: per-engine differences are anecdotal.",
    "- Thinking tokens are counted only when the provider reports them.",
    "- Cases are synthetic, written for this project, not real job applications.",
    "- Vault retrieval is keyword-only here; the semantic index used in the app is not exercised.",
    "",
  );

  return out.join("\n");
}
